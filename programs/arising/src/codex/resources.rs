impl ResourceKind {
    pub const COUNT: u16 = 315;

    pub const fn id(self) -> u16 {
        self as u16
    }

    pub const fn from_id(id: u16) -> Option<Self> {
        if id < Self::COUNT {
            // SAFETY: repr(u16) with contiguous variants guarded by range check.
            Some(unsafe { core::mem::transmute(id) })
        } else {
            None
        }
    }
}

impl AnchorSerialize for ResourceKind {
    fn serialize<W: Write>(&self, writer: &mut W) -> std::io::Result<()> {
        self.id().serialize(writer)
    }
}

impl AnchorDeserialize for ResourceKind {
    fn deserialize(buf: &mut &[u8]) -> std::io::Result<Self> {
        let id = u16::deserialize(buf)?;
        ResourceKind::from_id(id)
            .ok_or_else(|| Error::new(ErrorKind::InvalidData, "invalid resource kind"))
    }

    fn deserialize_reader<R: Read>(reader: &mut R) -> std::io::Result<Self> {
        let id = u16::deserialize_reader(reader)?;
        ResourceKind::from_id(id)
            .ok_or_else(|| Error::new(ErrorKind::InvalidData, "invalid resource kind"))
    }
}

